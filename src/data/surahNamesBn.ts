/**
 * Converts Quranic Latin phonetic transliteration into readable Bengali pronunciation.
 * Preserves clear syllable breaks for recitation assistance alongside Arabic Uthmani script.
 */
export function latinToBengaliPronunciation(raw: string): string {
  const clean = stripHtmlTags(raw)
    .replace(/[’']/g, 'আ')
    .replace(/[`‘]/g, 'আ')
    .replace(/Allaah/gi, 'আল্লা-হ')
    .replace(/Bismillaah/gi, 'বিসমিল্লা-হ');

  const words = clean.split(/\s+/);
  return words.map(transliterateWord).join(' ');
}

